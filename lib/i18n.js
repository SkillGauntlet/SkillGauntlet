let current = 'en';

export const LANGS = Object.keys(MESSAGES);

export function setLang(lang) {
  current = MESSAGES[lang] ? lang : 'en';
}

export function lang() {
  return current;
}

// SG_LANG wins; otherwise the OS locale; otherwise English.
export function detectLang(env = process.env) {
  const want = String(env.SG_LANG || '').toLowerCase().slice(0, 2);
  if (MESSAGES[want]) return want;
  const loc = Intl.DateTimeFormat().resolvedOptions().locale.toLowerCase().slice(0, 2);
  return MESSAGES[loc] ? loc : 'en';
}

export function t(key, vars = {}) {
  const table = MESSAGES[current] || MESSAGES.en;
  const raw = table[key] ?? MESSAGES.en[key] ?? key;
  return raw.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

// An error either carries a message key (translated) or is plain text from the runtime.
export function errorText(err) {
  if (!err.messageKey) return err.message;
  return t(err.messageKey, err.howKey ? { ...err.vars, how: t(err.howKey) } : err.vars);
}

// Comma-separated word list from the table, e.g. the accepted yes answers.
export function words(key) {
  return t(key).split(',').map((w) => w.trim().toLowerCase()).filter(Boolean);
}

export function messageTables() {
  return MESSAGES;
}
